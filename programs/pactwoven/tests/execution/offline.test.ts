type MetadataPatch = Partial<Pick<Stats, 'uid' | 'mode' | 'size' | 'nlink' | 'dev' | 'ino' | 'isFile' | 'isDirectory' | 'isSymbolicLink'>>;
async function withReceiptFilesystem(patches: Record<string, MetadataPatch>, work: (reads: string[], opens: () => number) => Promise<void>) {
  const raw = Buffer.from(JSON.stringify(rootReceipt()));
  const original = { lstat: promises.lstat, open: promises.open };
  const reads: string[] = []; let opens = 0;
  const metadata = (file: string): Stats => ({ uid: 0, gid: 0, mode: file.endsWith('.json') ? 0o100644 : 0o40755,
    size: file.endsWith('.json') ? raw.length : 0, nlink: 1, dev: 1, ino: 42, isFile: () => file.endsWith('.json'),
    isDirectory: () => !file.endsWith('.json'), isSymbolicLink: () => false, ...patches[file] }) as Stats;
  promises.lstat = (async (file: string) => {
    assert.ok(['/', '/work', '/work/receipts', '/work/receipts/canonical.json'].includes(file), 'Unexpected filesystem access');
    reads.push(file); return metadata(file);
  }) as typeof promises.lstat;
  promises.open = (async (file: string, flags: number) => {
    assert.equal(file, '/work/receipts/canonical.json'); assert.ok((flags & constants.O_NOFOLLOW) !== 0);
    opens++;
    return { async stat() { return { ...metadata(file), ...patches['fd'] }; }, async readFile() { return raw; }, async close() {} };
  }) as typeof promises.open;
  syncBuiltinESMExports();
  try { await work(reads, () => opens); }
  finally { promises.lstat = original.lstat; promises.open = original.open; syncBuiltinESMExports(); }
}

